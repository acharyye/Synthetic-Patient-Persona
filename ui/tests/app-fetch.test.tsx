/**
 * The API↔UI seam, tested where it actually breaks.
 *
 * The component tests in `components.test.tsx` pass `unquotable` as a PROP, so
 * they cannot see the fetch that reads it. `test_protocol_api.py` asserts the
 * server returns `unsupported`, so it cannot see the reader either. Both suites
 * were green across a release in which the two disagreed — and the thing that
 * disagreed was the product's signature claim: which numbers are judgement.
 *
 * So this file renders the real `App` with a stubbed `fetch` returning the SAME
 * committed fixture the Python tests read. If the server renames a key and
 * nobody touches `App.tsx`, this fails. That is the whole point: the seam is the
 * only place the two halves can silently part, and until now it was the only
 * place nobody looked.
 *
 * Fixture regenerated by: PYTHONPATH=src python scripts/export_schema.py
 */
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { render, screen, waitFor } from "@testing-library/react";
import { App } from "../src/App";
import assumptionsFixture from "../../tests/fixtures/assumptions.json";
import previewFixture from "../../tests/fixtures/scenario_preview.json";

const fixture = assumptionsFixture as unknown as {
  assumptions: { name: string; confidence: string }[];
  unsupported: string[];
};

beforeEach(() => {
  vi.stubGlobal(
    "fetch",
    vi.fn(async (input: RequestInfo | URL) => {
      const url = String(input);
      const body = url.includes("/assumptions") ? assumptionsFixture : previewFixture;
      return {
        ok: true,
        status: 200,
        json: async () => body,
      } as Response;
    }),
  );
});

afterEach(() => {
  vi.unstubAllGlobals();
  window.history.replaceState({}, "", "/");
});

describe("App reads the ledger response the server actually sends", () => {
  it("fires the never-quote badge from the live key name", async () => {
    render(<App />);
    // 18 of 20 shipped assumptions are unsupported. A "never quote" tag is only
    // reachable if the reader used the server's key — `unquotable` yielded an
    // empty Set and the tag never fired anywhere, header included.
    const tags = await screen.findAllByText("never quote");
    // The header renders " · 18 never quote" as one node, so these are the rows.
    expect(tags.length).toBe(fixture.unsupported.length);
  });

  it("names the count the fixture implies, not a number copied into a test", async () => {
    render(<App />);
    const expected = `· ${fixture.unsupported.length} never quote`;
    await waitFor(() =>
      expect(document.body.textContent).toContain(expected),
    );
  });

  it("marks the unquotable ROWS, not just the header", async () => {
    render(<App />);
    await waitFor(() => expect(screen.getAllByText("never quote").length)
      .toBeGreaterThanOrEqual(1));

    const lines = screen.getAllByTestId("ledger").flatMap(
      (ledger) => Array.from(ledger.querySelectorAll(".ledger-line")),
    );
    const never = lines.filter((row) => row.textContent?.includes("never quote"));
    expect(never.length).toBe(fixture.unsupported.length);

    // And they are the RIGHT ones — a set-membership bug that marks everything
    // would pass a count check.
    for (const row of never) {
      const name = row.querySelector(".name")?.textContent ?? "";
      expect(fixture.unsupported).toContain(name);
    }
  });

  it("leaves the measured assumptions styled as measured", async () => {
    render(<App />);
    await waitFor(() => expect(screen.getAllByText("never quote").length)
      .toBeGreaterThanOrEqual(1));

    const quotable = fixture.assumptions.filter(
      (a) => !fixture.unsupported.includes(a.name),
    );
    expect(quotable.length).toBeGreaterThan(0);
    for (const assumption of quotable) {
      expect(document.body.textContent).toContain(assumption.confidence);
    }
  });
});

describe("the fixture cannot drift from the server", () => {
  it("carries the key the reader uses", () => {
    // If someone renames `unsupported` server-side and regenerates the fixture,
    // this fails loudly instead of emptying a Set in a browser two weeks later.
    expect(Object.keys(assumptionsFixture)).toContain("unsupported");
    expect(Object.keys(assumptionsFixture)).not.toContain("unquotable");
  });

  it("has something to report, so the assertions above are not vacuous", () => {
    expect(fixture.unsupported.length).toBeGreaterThan(0);
    expect(fixture.unsupported.length).toBeLessThan(fixture.assumptions.length);
    expect(fixture.unsupported).toContain("timeline.dropout_hazard");
    expect(fixture.unsupported).toContain("narration.model");
  });
});
